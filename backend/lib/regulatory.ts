import type { State } from "./store";
import { categoryOf, filterAlerts, type ReportFilter } from "./report.ts";

// Regulatory outputs. These are DRAFTS for the compliance team: field names follow PPATK LTKM/STR (goAML) and OJK fraud
// reporting concepts, but the exact schema and submission must be checked against the regulator's current specification.
type Row = Record<string, string | number>;
const dt = (iso: string) => new Date(iso).toLocaleString("en-GB", { timeZone: "Asia/Jakarta" });
const jkt = (iso: string) => new Date(iso).toLocaleDateString("en-CA", { timeZone: "Asia/Jakarta" });

// Suspicious-transaction candidates: analyst-confirmed fraud plus any AML / blacklist hit in the period.
export function strRows(s: State, f: ReportFilter): Row[] {
  return filterAlerts(s, f).flatMap((a) => {
    const d = s.decisions.find((x) => x.alertId === a.id), aml = (a.hits ?? []).filter((h) => h.kind === "BLACKLIST" || h.kind === "AML");
    if (d?.label !== "FRAUD" && !aml.length) return [];
    const tx = s.transactions.find((t) => t.id === a.transactionId)!, c = s.customers.find((x) => x.id === a.customerId)!;
    return [{
      "Report Ref": `STR-${a.id}`, "Transaction Date": dt(tx.createdAt), "Transaction ID": tx.id, "CIF": c.id, "Customer Name": c.name, "Customer Account": c.accountId,
      "Amount (IDR)": tx.amount, "Currency": tx.currency, "Channel": tx.channel, "Beneficiary Name": tx.beneficiary.name, "Beneficiary Bank": tx.beneficiary.bankName, "Beneficiary Account": tx.beneficiary.accountId,
      "Suspicion Indicator": categoryOf(s, a), "Watchlist / AML": aml.map((h) => `${h.kind}: ${h.detail || h.value}`).join(" | "),
      "Analyst Decision": d?.action ?? "Pending", "Outcome": d?.label ?? "", "Decided By": d?.decidedBy ?? "", "Decision Date": d ? dt(d.decidedAt) : "", "Case ID": a.caseId ?? "", "Narrative": d?.reason ?? "",
    }];
  });
}

const esc = (v: unknown) => String(v ?? "").replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
// goAML-style XML draft, one <report> per candidate.
export function strXml(rows: Row[], reportingEntity = "FORTIFY-DEMO") {
  const r = rows.map((x) => `  <report>
    <rentity_id>${esc(reportingEntity)}</rentity_id><submission_code>E</submission_code><report_code>STR</report_code>
    <entity_reference>${esc(x["Report Ref"])}</entity_reference><submission_date>${new Date().toISOString().slice(0, 19)}</submission_date><currency_code_local>IDR</currency_code_local>
    <reason>${esc(`${x["Suspicion Indicator"]}. ${x["Watchlist / AML"]} ${x["Narrative"]}`.trim())}</reason>
    <transaction>
      <transactionnumber>${esc(x["Transaction ID"])}</transactionnumber><date_transaction>${esc(x["Transaction Date"])}</date_transaction><transmode_code>${esc(x["Channel"])}</transmode_code><amount_local>${esc(x["Amount (IDR)"])}</amount_local>
      <t_from_my_client><from_account><account>${esc(x["Customer Account"])}</account><signatory><t_person><first_name>${esc(x["Customer Name"])}</first_name><id_number>${esc(x["CIF"])}</id_number></t_person></signatory></from_account></t_from_my_client>
      <t_to><to_account><institution_name>${esc(x["Beneficiary Bank"])}</institution_name><account>${esc(x["Beneficiary Account"])}</account><account_name>${esc(x["Beneficiary Name"])}</account_name></to_account></t_to>
    </transaction>
  </report>`).join("\n");
  return `<?xml version="1.0" encoding="UTF-8"?>\n<!-- DRAFT generated by FraudSight AI. Validate against the current PPATK goAML schema before submission. -->\n<reports>\n${r}\n</reports>\n`;
}

// OJK-style fraud summary by category for the period.
export function ojkRows(s: State, f: ReportFilter): Row[] {
  const m = new Map<string, { cases: number; attempted: number; prevented: number; loss: number }>();
  for (const a of filterAlerts(s, f)) {
    const d = s.decisions.find((x) => x.alertId === a.id);
    if (d?.label !== "FRAUD") continue;
    const k = categoryOf(s, a), v = m.get(k) ?? { cases: 0, attempted: 0, prevented: 0, loss: 0 };
    v.cases++; v.attempted += d.amount;
    if (d.action === "APPROVE") v.loss += d.amount; else v.prevented += d.amount;
    m.set(k, v);
  }
  const rows: Row[] = [...m].map(([k, v]) => ({ "Fraud Category": k, "Cases": v.cases, "Attempted Amount (IDR)": v.attempted, "Prevented Amount (IDR)": v.prevented, "Actual Loss (IDR)": v.loss, "Recovery Rate": v.attempted ? `${((v.prevented / v.attempted) * 100).toFixed(1)}%` : "—" }));
  const t = [...m.values()].reduce((x, v) => ({ cases: x.cases + v.cases, attempted: x.attempted + v.attempted, prevented: x.prevented + v.prevented, loss: x.loss + v.loss }), { cases: 0, attempted: 0, prevented: 0, loss: 0 });
  rows.push({ "Fraud Category": `TOTAL (${f.from ?? "start"} to ${f.to ?? "today"})`, "Cases": t.cases, "Attempted Amount (IDR)": t.attempted, "Prevented Amount (IDR)": t.prevented, "Actual Loss (IDR)": t.loss, "Recovery Rate": t.attempted ? `${((t.prevented / t.attempted) * 100).toFixed(1)}%` : "—" });
  return rows;
}

export function auditRows(s: State, f: ReportFilter): Row[] {
  const q = f.q?.trim().toLowerCase();
  return [...s.audit].reverse().filter((e) => (!f.from || jkt(e.at) >= f.from) && (!f.to || jkt(e.at) <= f.to) &&
    (!q || [e.id, e.actor, e.entityType, e.entityId, e.action, e.reason ?? ""].some((v) => v.toLowerCase().includes(q))))
    .map((e) => ({ "Audit ID": e.id, "Time": dt(e.at), "Actor": e.actor, "Entity": e.entityType, "Entity ID": e.entityId, "Action": e.action, "Reason": e.reason ?? "", "AI Recommendation": e.aiRecommendation ?? "", "Before": JSON.stringify(e.before), "After": JSON.stringify(e.after) }));
}
